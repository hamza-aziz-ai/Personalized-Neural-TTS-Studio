BASE_DIRECTORY = Path(__file__).resolve().parent
OUTPUT_DIRECTORY = BASE_DIRECTORY / "outputs"


def find_model_directory() -> Path:
    """Find models in the package, an environment override, or parent folder.

    Returns:
        First candidate directory containing at least one ``.onnx`` model. If no
        candidate is populated, the package-local ``models`` directory is returned
        so the interface can display an actionable download command.
    """

    configured_directory = os.getenv("PIPER_MODEL_DIR")
    candidates = [
        Path(configured_directory) if configured_directory else None,
        BASE_DIRECTORY / "models",
        BASE_DIRECTORY.parent / "models",
    ]
    for candidate in candidates:
        if candidate is not None and candidate.exists() and any(candidate.glob("*.onnx")):
            return candidate
    return BASE_DIRECTORY / "models"


@st.cache_resource(show_spinner=False)
def get_cached_voice(model_path: str):
    """Load and cache one Piper voice across Streamlit reruns.

    Args:
        model_path: String path used as the stable Streamlit cache key.

    Returns:
        Loaded Piper voice model, GPU-accelerated when CUDA is usable.
    """

    return load_piper_voice(Path(model_path), prefer_gpu=True)


def format_metric_rows(metrics: dict[str, float]) -> list[dict[str, str]]:
    """Convert raw metric values into a compact presentation table.

    Args:
        metrics: Numeric metrics generated by ``tts_core``.

    Returns:
        List of dictionaries accepted directly by ``st.dataframe``.
    """

    return [
        {"Metric": "Audio duration", "Value": f"{metrics['duration_seconds']:.2f} s"},
        {"Metric": "Response time", "Value": f"{metrics['latency_seconds']:.2f} s"},
        {"Metric": "Real-time factor", "Value": f"{metrics['real_time_factor']:.3f}"},
        {"Metric": "Estimated pace", "Value": f"{metrics['estimated_wpm']:.0f} WPM"},
        {"Metric": "RMS level", "Value": f"{metrics['rms_dbfs']:.2f} dBFS"},
        {"Metric": "Peak level", "Value": f"{metrics['peak_dbfs']:.2f} dBFS"},
        {"Metric": "Clipping", "Value": f"{metrics['clipping_percent']:.4f}%"},
        {"Metric": "Silence frames", "Value": f"{metrics['silence_percent']:.2f}%"},
        {
            "Metric": "Spectral centroid",
            "Value": f"{metrics['spectral_centroid_hz']:.0f} Hz",
        },
    ]


def estimate_sentence_count(text: str) -> int:
    """Roughly count sentences to size a synthesis progress bar.

    Piper yields one audio chunk per sentence, so this only needs to be a
    reasonable denominator for a progress fraction, not an exact count.

    Args:
        text: Raw text as currently typed in the UI.

    Returns:
        Estimated sentence count, at least 1.
    """

    return max(len(re.findall(r"[.!?]+(?:\s|$)", text.strip())), 1)



model_directory = find_model_directory()
input_column, settings_column = st.columns([1.65, 1.0], gap="large")

with input_column:
    st.subheader("1. Enter text")
    max_characters = st.number_input(
        "Max characters",
        min_value=100,
        max_value=20_000,
        value=MAX_TEXT_CHARACTERS,
        step=100,
        help="Raise for longer passages. Longer text takes proportionally "
        "longer to synthesize.",
    )
    text_input = st.text_area(
        "Text to synthesize",
        value=DEFAULT_TEXT,
        height=145,
        help="Punctuation improves prosody.",
    )
    st.caption(f"{len(text_input)} / {max_characters} characters")

with settings_column:
    st.subheader("2. Customize speech")
    voice_label = st.selectbox(
        "Neural voice",
        options=list(VOICE_CATALOG),
        format_func=lambda label: f"{label} — {VOICE_CATALOG[label]['display_name']}",
    )
    rate_multiplier = st.slider(
        "Speaking-rate multiplier",
        min_value=float(MIN_RATE_MULTIPLIER),
        max_value=float(MAX_RATE_MULTIPLIER),
        value=1.00,
        step=0.05,
        help="Values below 1.0 are slower; values above 1.0 are faster.",
    )
    pitch_semitones = st.slider(
        "Pitch shift (semitones)",
        min_value=float(MIN_PITCH_SEMITONES),
        max_value=float(MAX_PITCH_SEMITONES),
        value=0.0,
        step=0.5,
        help="Applied after synthesis; 0 retains the authentic trained voice.",
    )

generate_clicked = st.button(
    "Generate personalized speech",
    type="primary",
    width="stretch",
)

# The demo query parameter enables a deterministic generated-result screenshot
# without changing the normal interactive workflow used by students or evaluators.
demo_mode = st.query_params.get("demo") == "1"
should_generate = generate_clicked or (
    demo_mode and "latest_synthesis" not in st.session_state
)

if should_generate:
    try:
        selected_model_path = resolve_model_path(model_directory, voice_label)
        with st.spinner("Loading the neural voice..."):
            cached_voice = get_cached_voice(str(selected_model_path.resolve()))
            active_provider = cached_voice.session.get_providers()[0]

        estimated_sentences = estimate_sentence_count(text_input)
        progress_bar = st.progress(0.0, text="Synthesizing speech...")

        def report_progress(chunk_count: int, total: int = estimated_sentences) -> None:
            progress_bar.progress(
                min(chunk_count / total, 1.0),
                text=f"Synthesizing speech... ({chunk_count}/{total} sentences)",
            )

        synthesis_result = synthesize_speech(
            cached_voice,
            text_input,
            voice_label=voice_label,
            rate_multiplier=rate_multiplier,
            pitch_semitones=pitch_semitones,
            max_characters=max_characters,
            on_chunk=report_progress,
        )
        progress_bar.empty()
        output_name = f"latest_{voice_label.lower()}_speech.wav"
        save_synthesis_result(synthesis_result, OUTPUT_DIRECTORY / output_name)
        st.session_state["latest_synthesis"] = synthesis_result
        st.session_state["active_provider"] = active_provider
    except (FileNotFoundError, TypeError, ValueError, RuntimeError) as error:
        st.error(str(error))
        if isinstance(error, FileNotFoundError):
            st.code("python download_models.py", language="bash")

if "latest_synthesis" in st.session_state:
    result = st.session_state["latest_synthesis"]
    st.divider()
    st.subheader("3. Generated output and evaluation")

    audio_column, metric_column = st.columns([1.15, 1.0], gap="large")
    with audio_column:
        st.audio(result.wav_bytes, format="audio/wav")
        download_filename = (
            f"group16_{result.voice_label.lower()}_rate-"
            f"{result.rate_multiplier:.2f}_pitch-{result.pitch_semitones:+.1f}.wav"
        )
        st.download_button(
            "Download WAV",
            data=result.wav_bytes,
            file_name=download_filename,
            mime="audio/wav",
            width="stretch",
        )
        provider_label = st.session_state.get("active_provider", "CPUExecutionProvider")
        device_label = "GPU (CUDA)" if provider_label == "CUDAExecutionProvider" else "CPU"
        st.markdown(
            f"**Voice:** {result.voice_label}  \n"
            f"**Rate:** {result.rate_multiplier:.2f}x  \n"
            f"**Pitch:** {result.pitch_semitones:+.1f} semitones  \n"
            f"**Sampling rate:** {result.sample_rate:,} Hz  \n"
            f"**Inference device:** {device_label}"
        )

    with metric_column:
        metric_a, metric_b, metric_c = st.columns(3)
        metric_a.metric("Response", f"{result.metrics['latency_seconds']:.2f} s")
        metric_b.metric("Duration", f"{result.metrics['duration_seconds']:.2f} s")
        metric_c.metric("RTF", f"{result.metrics['real_time_factor']:.3f}")
        st.dataframe(
            format_metric_rows(result.metrics),
            hide_index=True,
            width="stretch",
        )

    for observation in summarize_quality(result.metrics):
        st.info(observation)

    diagnostic_figure = create_audio_diagnostic_figure(
        result.waveform,
        result.sample_rate,
        title=f"{result.voice_label} voice: waveform and mel representation",
    )
    st.pyplot(diagnostic_figure, width="stretch")
    plt.close(diagnostic_figure)

    with st.expander("Listener MOS evaluation (1 = bad, 5 = excellent)"):
        st.caption(
            "Submit only a rating you personally assigned after listening. "
            "Responses are appended to outputs/mos_feedback.csv."
        )
        with st.form("mos_feedback_form", clear_on_submit=True):
            mos_column, naturalness_column, clarity_column = st.columns(3)
            overall_mos = mos_column.slider("Overall MOS", 1, 5, 4)
            naturalness = naturalness_column.slider("Naturalness", 1, 5, 4)
            clarity = clarity_column.slider("Clarity", 1, 5, 4)
            comments = st.text_input("Optional comments")
            feedback_submitted = st.form_submit_button("Save genuine listener rating")
            if feedback_submitted:
                feedback_path = append_mos_feedback(
                    OUTPUT_DIRECTORY / "mos_feedback.csv",
                    result.voice_label,
                    result.rate_multiplier,
                    result.pitch_semitones,
                    overall_mos,
                    naturalness,
                    clarity,
                    comments,
                )
                st.success(f"Rating saved to {feedback_path.name}.")

